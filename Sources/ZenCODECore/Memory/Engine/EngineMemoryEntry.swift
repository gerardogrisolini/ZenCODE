import Foundation

let unspecifiedEmbeddingModel = "unspecified"

enum TrustLevel: String, Codable, Sendable, CaseIterable {
    case high
    case medium
    case low
}

enum EngineMemoryScope: String, Codable, Sendable, CaseIterable {
    case project
    case global
    case all

    public var includesProject: Bool { self == .project || self == .all }
    public var includesGlobal: Bool { self == .global || self == .all }
}

enum EngineMemoryCategory: Hashable, Sendable {
    case fact
    case preference
    case entity
    case correction
    case custom(String)

    public var rawValue: String {
        switch self {
        case .fact: "fact"
        case .preference: "preference"
        case .entity: "entity"
        case .correction: "correction"
        case .custom(let value): value
        }
    }
}

extension EngineMemoryCategory: Codable {
    private enum CustomKey: String, CodingKey { case custom }

    public init(from decoder: Decoder) throws {
        if let value = try? decoder.singleValueContainer().decode(String.self) {
            switch value {
            case "fact": self = .fact
            case "preference": self = .preference
            case "entity": self = .entity
            case "correction": self = .correction
            default: self = .custom(value)
            }
            return
        }
        let container = try decoder.container(keyedBy: CustomKey.self)
        self = .custom(try container.decode(String.self, forKey: .custom))
    }

    public func encode(to encoder: Encoder) throws {
        switch self {
        case .custom(let value):
            var container = encoder.container(keyedBy: CustomKey.self)
            try container.encode(value, forKey: .custom)
        default:
            var container = encoder.singleValueContainer()
            try container.encode(rawValue)
        }
    }
}

struct Reinforcement: Codable, Sendable, Equatable {
    public var sessionID: String
    public var messageIndex: Int
    public var timestamp: Date

    public init(sessionID: String, messageIndex: Int, timestamp: Date = Date()) {
        self.sessionID = sessionID
        self.messageIndex = messageIndex
        self.timestamp = timestamp
    }
}

struct EngineMemoryEntry: Codable, Sendable, Identifiable, Equatable {
    public var id: String
    public var category: EngineMemoryCategory
    public var content: String
    public var tags: [String]
    public var searchText: String
    public var createdAt: Date
    public var updatedAt: Date
    public var accessCount: UInt32
    public var source: String?
    public var trust: TrustLevel
    public var strength: UInt32
    public var active: Bool
    public var supersededBy: String?
    public var reinforcements: [Reinforcement]
    /// The entry's vector, always held at the precision the vectors file
    /// stores (`MemoryVectorFile.storedComponentType`): assigning rounds every
    /// component, so a graph in memory is exactly what saving and reloading it
    /// returns, and writing back an equal vector never looks like a change.
    /// Rounding a vector that is already at that precision keeps its storage.
    public var embedding: [Float]? {
        get { storedEmbedding }
        set { storedEmbedding = newValue.map(MemoryVectorFile.storedComponentType.rounded) }
    }
    private var storedEmbedding: [Float]?
    public var embeddingModel: String?
    public var confidence: Float
    public var scope: EngineMemoryScope
    /// Provenance for the leading `Timestamp:` annotation written by
    /// `memory.write`. Content alone cannot distinguish that annotation from
    /// an identical machine-shaped value explicitly supplied by an author.
    public var autoGeneratedTimestamp: Bool

    public init(
        id: String? = nil,
        category: EngineMemoryCategory,
        content: String,
        tags: [String] = [],
        source: String? = nil,
        trust: TrustLevel = .medium,
        scope: EngineMemoryScope = .project,
        createdAt: Date = Date(),
        updatedAt: Date? = nil,
        embedding: [Float]? = nil,
        embeddingModel: String? = nil,
        confidence: Float = 1.0,
        autoGeneratedTimestamp: Bool = false
    ) {
        self.id = id ?? Self.makeID()
        self.category = category
        self.content = content
        self.tags = tags
        self.searchText = Self.normalizeSearchText(content: content, tags: tags)
        self.createdAt = createdAt
        self.updatedAt = updatedAt ?? createdAt
        self.accessCount = 0
        self.source = source
        self.trust = trust
        self.strength = 1
        self.active = true
        self.supersededBy = nil
        self.reinforcements = []
        self.storedEmbedding = embedding.map(MemoryVectorFile.storedComponentType.rounded)
        self.embeddingModel = embeddingModel
        self.confidence = min(max(confidence, 0), 1)
        self.scope = scope
        self.autoGeneratedTimestamp = autoGeneratedTimestamp
    }

    public var effectiveEmbeddingModel: String {
        embeddingModel ?? unspecifiedEmbeddingModel
    }

    public func embeddingMatches(model: String) -> Bool {
        embedding != nil && effectiveEmbeddingModel == model
    }

    public mutating func refreshSearchText() {
        searchText = Self.normalizeSearchText(content: content, tags: tags)
    }

    public var searchableText: String {
        searchText.isEmpty ? Self.normalizeSearchText(content: content, tags: tags) : searchText
    }

    /// Retrieval weight: stored confidence, discounted by the age of the last
    /// content change (`max(createdAt, updatedAt)`: a write, an update or an
    /// archive toggle; retrieval maintenance never touches `updatedAt`), and
    /// lifted by a logarithmic access boost. See ``MemoryAgePolicy``.
    public func effectiveConfidence(
        at date: Date = Date(),
        policy: MemoryAgePolicy = .default
    ) -> Float {
        let lastChange = max(createdAt, updatedAt)
        let ageDays = max(0, Float(date.timeIntervalSince(lastChange) / 86_400))
        let discount = policy.discount(ageDays: ageDays, category: category)
        let accessBoost = 1 + 0.1 * logf(Float(accessCount) + 1)
        return min(confidence * discount * accessBoost, 1)
    }

    /// Records a selection: the stored confidence rises and the access count
    /// grows. `updatedAt` is left alone on purpose, so being recalled does not
    /// make an entry look recently changed and keep it young for ever.
    public mutating func boostConfidence(by amount: Float) {
        confidence = min(confidence + amount, 1)
        accessCount &+= 1
    }

    public mutating func decayConfidence(by amount: Float) {
        confidence = max(confidence - amount, 0)
    }

    /// Counts an access without changing the content timestamp.
    public mutating func touch() {
        accessCount &+= 1
    }

    public mutating func reinforce(sessionID: String, messageIndex: Int) {
        strength &+= 1
        updatedAt = Date()
        reinforcements.append(
            Reinforcement(sessionID: sessionID, messageIndex: messageIndex)
        )
    }

    public mutating func supersede(with newID: String) {
        active = false
        supersededBy = newID
    }

    public mutating func setEmbedding(_ values: [Float]?, model: String?) {
        embedding = values
        embeddingModel = model
    }

    /// Stores `values` exactly as given, without rounding them to the stored
    /// precision. For callers that guarantee the values are already at that
    /// precision (the vectors-file decoder, widening binary16 components), and
    /// for the A/B harness, which compares full-precision vectors with stored
    /// ones on a graph it never saves: a graph holding a vector that is not at
    /// the stored precision is not what saving and reloading it would return.
    mutating func setEmbeddingWithoutRounding(_ values: [Float]?, model: String?) {
        storedEmbedding = values
        embeddingModel = model
    }

    public static func normalizeSearchText(content: String, tags: [String]) -> String {
        ([content] + tags)
            .joined(separator: " ")
            .lowercased()
            .split { !$0.isLetter && !$0.isNumber }
            .map(String.init)
            .joined(separator: " ")
    }

    private enum CodingKeys: String, CodingKey {
        case id, category, content, tags, searchText, createdAt, updatedAt, accessCount
        case source, trust, strength, active, supersededBy, reinforcements
        case embedding, embeddingModel, confidence, scope, autoGeneratedTimestamp
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        category = try c.decode(EngineMemoryCategory.self, forKey: .category)
        content = try c.decode(String.self, forKey: .content)
        tags = try c.decodeIfPresent([String].self, forKey: .tags) ?? []
        searchText = try c.decodeIfPresent(String.self, forKey: .searchText)
            ?? Self.normalizeSearchText(content: content, tags: tags)
        createdAt = try c.decode(Date.self, forKey: .createdAt)
        updatedAt = try c.decodeIfPresent(Date.self, forKey: .updatedAt) ?? createdAt
        accessCount = try c.decodeIfPresent(UInt32.self, forKey: .accessCount) ?? 0
        source = try c.decodeIfPresent(String.self, forKey: .source)
        trust = try c.decodeIfPresent(TrustLevel.self, forKey: .trust) ?? .medium
        strength = try c.decodeIfPresent(UInt32.self, forKey: .strength) ?? 1
        active = try c.decodeIfPresent(Bool.self, forKey: .active) ?? true
        supersededBy = try c.decodeIfPresent(String.self, forKey: .supersededBy)
        reinforcements = try c.decodeIfPresent([Reinforcement].self, forKey: .reinforcements) ?? []
        // Up to graph version 3 the vector is inline: a base64 string from
        // version 3, a numeric array before (see `EmbeddingWireCoding`). From
        // version 4 it lives in the vectors file and the key is absent; the
        // persistence attaches it after decoding.
        if let wire = try c.decodeIfPresent(EmbeddingWireValue.self, forKey: .embedding) {
            guard let values = wire.components else {
                throw DecodingError.dataCorruptedError(
                    forKey: .embedding,
                    in: c,
                    debugDescription: "Expected a base64 string of little-endian binary32 components."
                )
            }
            storedEmbedding = MemoryVectorFile.storedComponentType.rounded(values)
        } else {
            storedEmbedding = nil
        }
        embeddingModel = try c.decodeIfPresent(String.self, forKey: .embeddingModel)
        confidence = try c.decodeIfPresent(Float.self, forKey: .confidence) ?? 1
        scope = try c.decodeIfPresent(EngineMemoryScope.self, forKey: .scope) ?? .project
        autoGeneratedTimestamp = try c.decodeIfPresent(Bool.self, forKey: .autoGeneratedTimestamp) ?? false
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(id, forKey: .id)
        try c.encode(category, forKey: .category)
        try c.encode(content, forKey: .content)
        try c.encode(tags, forKey: .tags)
        if !searchText.isEmpty { try c.encode(searchText, forKey: .searchText) }
        try c.encode(createdAt, forKey: .createdAt)
        try c.encode(updatedAt, forKey: .updatedAt)
        try c.encode(accessCount, forKey: .accessCount)
        try c.encodeIfPresent(source, forKey: .source)
        try c.encode(trust, forKey: .trust)
        try c.encode(strength, forKey: .strength)
        try c.encode(active, forKey: .active)
        try c.encodeIfPresent(supersededBy, forKey: .supersededBy)
        if !reinforcements.isEmpty { try c.encode(reinforcements, forKey: .reinforcements) }
        // The vector is not part of the JSON from graph version 4 on: the
        // persistence writes it to the vectors file (`MemoryVectorFile`).
        try c.encodeIfPresent(embeddingModel, forKey: .embeddingModel)
        try c.encode(confidence, forKey: .confidence)
        try c.encode(scope, forKey: .scope)
        if autoGeneratedTimestamp { try c.encode(autoGeneratedTimestamp, forKey: .autoGeneratedTimestamp) }
    }

    private static func makeID() -> String {
        let millis = Int64(Date().timeIntervalSince1970 * 1_000)
        return "mem_\(millis)_\(UUID().uuidString.lowercased())"
    }
}
