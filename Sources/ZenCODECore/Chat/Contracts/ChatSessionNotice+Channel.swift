extension ChatSessionNotice {
    /// The tone a text channel writes this notice in.
    public var channel: ChatSessionNoticeChannel {
        switch self {
        case .operationFailed,
             .unknownCommand,
             .commandUnavailable,
             .thinkingTakesNoArguments,
             .noPendingPlanApproval,
             .runtimeSessionUnavailable,
             .projectAgentsSaveFailed,
             .skillInstallSourceRequired,
             .savedSessionNotFound,
             .nothingToSave,
             .sessionUnavailableToSave,
             .noActiveSavedSession,
             .activeSavedSessionNotFound,
             .checkpointEntryUnknown,
             .checkpointEntryNotFound,
             .subAgentToolsRequired,
             .agentRoleUnavailable,
             .planMissingGoal,
             .planDiscussionBlocksMutation,
             .planUnavailableForSaving,
             .activePlanAlreadyExists,
             .savedPlanUnavailable,
             .savedPlansAllCompleted,
             .savedPlanContextNotAdded,
             .planDeleteUsage,
             .savedPlanNotFound,
             .savedPlanAmbiguous,
             .planUnavailableForApproval,
             .workflowMissingGoal,
             .workflowBlockedByPlan,
             .workflowAlreadyActive,
             .taskIDRequired,
             .unknownTasksAction,
             .fileChangesUndoFailed,
             .artifactsTakeNoArguments,
             .openTargetNotFound,
             .invalidAttachmentSelection,
             .unterminatedAttachmentQuote:
            return .failure
        case .savedPlanLoaded,
             .savedPlans,
             .planStatus,
             .queuedPlans,
             .taskDetail,
             .fileArtifacts:
            return .markdown
        case let .requiresInteractiveHost(operation):
            return operation.channel
        case let .engineCheckpoint(notice):
            return notice.channel
        case .modelSelected,
             .modelUnchanged,
             .noCurrentModel,
             .thinkingNotSupported,
             .thinkingUnchanged,
             .selectedAgent,
             .availableAgents,
             .projectAgentsAssociated,
             .agentSwitched,
             .activeTools,
             .toolSelectionUsage,
             .selectedSkills,
             .skillSelectionUsage,
             .noPromptSkillsInstalled,
             .noSkillsSelectedForUninstall,
             .skillsUninstalled,
             .skillInstallStarted,
             .skillInstalled,
             .workspaceAccessDenied,
             .sessionStarted,
             .noSavedSessions,
             .sessionSelectionUsage,
             .savedSessions,
             .sessionDeleted,
             .sessionSaved,
             .nothingToCompact,
             .turnMemoryBlock,
             .noTurnMemoryBlock,
             .sessionCompacted,
             .sessionLoaded,
             .checkpointRestored,
             .help,
             .noSavedPlans,
             .planSaved,
             .planSequenceSaved,
             .savedPlansDeleted,
             .planClarificationActive,
             .planAwaitingApprovalGoal,
             .noActivePlan,
             .planApprovalGoalPrompt,
             .planApproved,
             .planDiscussionCleared,
             .noPlanToClear,
             .activePlanCleared,
             .noChangesToReview,
             .noTaskGraph,
             .taskRetried,
             .taskCancelled,
             .taskGraphsCleared,
             .taskGraphResumed,
             .taskGraphResumeFailed,
             .oldTaskGraphsDeleted,
             .oldTaskGraphsDeleteFailed,
             .noTrackedFileChanges,
             .fileChangeSummary,
             .fileChangesReverted,
             .fileChangesNotUndone,
             .noFileArtifacts,
             .noOpenCandidates,
             .nothingOpened,
             .opening,
             .attachmentUsage,
             .attachmentDeleteUsage,
             .attachmentSelectionCancelled,
             .attachmentsAdded,
             .noPendingAttachments,
             .pendingAttachments,
             .pendingAttachmentsRemoved,
             .attachmentRemoved,
             .attachmentDirectoryUnreadable,
             .noAttachableFiles:
            return .system
        }
    }
}
