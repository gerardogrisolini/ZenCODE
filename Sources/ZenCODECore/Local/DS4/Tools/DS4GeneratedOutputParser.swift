//
//  DS4GeneratedOutputParser.swift
//  ZenCODE
//
//  Streaming projection of DS4 generated text, modelled on ds4-agent's
//  agent_stream_text/agent_stream_normal_byte (ds4_agent.c): reasoning is split
//  from visible text, the native tool-call block is hidden and parsed, and
//  malformed markup becomes a DS4ToolParseError the model can retry from.
//

import Foundation
import ToolCore

/// A streamed piece of generated output.
enum DS4ParsedOutputDelta: Sendable, Equatable {
    case visible(String)
    case thought(String)
}

/// The result of one generated assistant turn.
struct DS4ParsedOutput: Sendable {
    /// Visible answer text, without reasoning and without any tool markup.
    let visibleText: String
    /// Reasoning text from `<think>…</think>` spans.
    let reasoningText: String
    /// Executable tool calls. Empty whenever `parseError` is set: like
    /// ds4-agent, a malformed block executes nothing.
    let toolCalls: [DirectAgentToolCall]
    /// `toolCalls` with arguments in the order the model emitted them, for an
    /// exact replay through `DS4ToolCallRenderer` (DirectAgentToolCall keeps a
    /// key-sorted canonical JSON).
    let toolCallReplays: [DS4ToolCallReplay]
    /// Malformed or incomplete tool-call output, to be returned to the model.
    let parseError: DS4ToolParseError?
    /// Every chunk passed to `consume(_:)`, concatenated.
    let rawText: String
    /// Deltas released by `finish()` (text held back while it could still
    /// have started a marker). Already included in `visibleText`/`reasoningText`.
    let finalDeltas: [DS4ParsedOutputDelta]
}

/// Streaming parser for the text generated by a DS4 model.
///
/// Feed every committed token's text to `consume(_:)` (an empty string is
/// valid, e.g. while a UTF-8 decoder holds an incomplete scalar) and read
/// `shouldStopGeneration`/`wantsGreedySampling` right after: both are updated
/// synchronously. Call `finish()` once generation ends.
///
/// Behaviour mirrors ds4-agent:
/// - `<think>`/`</think>` are recognized only outside a tool block; tags inside
///   argument values are literal data;
/// - the visible stream never shows tool markup, not even partially: suffixes
///   that may start a marker are held back and released once they cannot;
/// - the tool block is recognized with ds4-agent's tolerated openers (DSML:
///   canonical, missing leading bar, bare `<｜DSML｜invoke` as an implicit
///   `tool_calls` wrapper);
/// - generation must stop once the block completes (DSML at the closing
///   `tool_calls` tag; GLM/Qwen after the last `</tool_call>` at the first
///   byte that does not start another `<tool_call>`, or at end of generation):
///   later text is dropped, like ds4-agent which stops sampling there;
/// - a tool call inside a reasoning span, DSML markup outside a valid block
///   (DSML syntaxes only), malformed or incomplete blocks set `parseError` and
///   request a stop.
struct DS4GeneratedOutputParser: Sendable {
    private enum Terminal: Sendable, Equatable {
        case completed
        case failed(String)
    }

    /// Released display bytes of one channel, in stream order.
    private struct Run: Sendable {
        let thought: Bool
        var bytes: [UInt8]
    }

    /// `agent_dsml_marker_detector`.
    private struct MarkerDetector: Sendable {
        static let markers: [[UInt8]] = [
            Array("｜DSML｜".utf8),
            Array("|DSML|".utf8),
            Array("<DSML｜".utf8),
            Array("</DSML｜".utf8),
        ]

        private var tail: [UInt8] = []

        mutating func feed(_ byte: UInt8) -> [UInt8]? {
            if tail.count == 32 {
                tail.removeFirst()
            }
            tail.append(byte)
            return Self.markers.first { DS4Bytes.hasSuffix(tail, $0) }
        }

        mutating func reset() {
            tail.removeAll()
        }
    }

    static let thinkingToolCallDetail = "tool calling is not allowed inside <think></think>"
    static let strayDSMLDetail = "DSML markup outside a valid tool_calls block"

    let syntax: DS4ToolSyntax
    let parameterTypes: [String: [String: DS4ToolParameterKind]]

    private var splitter: DS4ThinkSplitter
    private var tool: DS4ToolCallStreamParser
    private(set) var isInsideThinking: Bool
    private var toolActive = false
    private var startTail: [UInt8] = []
    private var thinkingMarkers = MarkerDetector()
    private var plainMarkers = MarkerDetector()
    /// Written bytes held back because they may still start a DSML marker.
    private var heldVisible: [UInt8] = []
    private var heldThought: [UInt8] = []
    private var runs: [Run] = []
    /// Trailing bytes of an incomplete UTF-8 scalar, per channel.
    private var undecodedVisible: [UInt8] = []
    private var undecodedThought: [UInt8] = []
    private var terminal: Terminal?
    private var rawText = ""
    private var visibleText = ""
    private var reasoningText = ""
    private var finishedOutput: DS4ParsedOutput?

    private let startForms: [(bytes: [UInt8], implicitInvoke: Bool)]
    private let canonicalInvoke: [UInt8]

    /// - Parameters:
    ///   - startsInsideThinking: whether the assistant prefix already opened a
    ///     reasoning span; see `DS4ToolSyntax.outputStartsInsideThinking`.
    ///   - parameterTypes: tool → parameter → declared kind, from
    ///     `DS4ToolParameterKind.map(from:)`.
    init(
        syntax: DS4ToolSyntax,
        startsInsideThinking: Bool,
        parameterTypes: [String: [String: DS4ToolParameterKind]] = [:]
    ) {
        self.syntax = syntax
        self.parameterTypes = parameterTypes
        self.splitter = DS4ThinkSplitter(startsInThinking: startsInsideThinking)
        self.tool = DS4ToolCallStreamParser(syntax: syntax)
        self.isInsideThinking = startsInsideThinking
        self.canonicalInvoke = Array(syntax.dsmlOpenTag(.invoke).utf8)
        switch syntax {
        case .glm, .qwen:
            self.startForms = [(Array("<tool_call>".utf8), false)]
        case .dsml, .dsml41:
            // agent_stream_dsml_start_match
            let calls = syntax.dsmlTagName(.toolCalls)
            let invoke = syntax.dsmlTagName(.invoke)
            self.startForms = [
                (Array("<｜DSML｜\(calls)>".utf8), false),
                (Array("<DSML｜\(calls)>".utf8), false),
                (Array("<｜DSML｜\(invoke)".utf8), true),
                (Array("<DSML｜\(invoke)".utf8), true),
            ]
        }
    }

    /// Generation must stop after the token just consumed: the tool block is
    /// complete or the output is malformed.
    var shouldStopGeneration: Bool {
        terminal != nil
    }

    /// The next token should be sampled greedily
    /// (`agent_stream_wants_greedy_sampling`): a DSML-shaped opener is being
    /// held, the block is between structural tags, or a value's closing tag is
    /// being streamed.
    var wantsGreedySampling: Bool {
        guard terminal == nil else {
            return false
        }
        if startTail.count > 1 {
            return true
        }
        guard toolActive else {
            return false
        }
        switch tool.state {
        case .structural:
            return true
        case .parameterValue:
            return tool.parameterClosePrefix
        case .search, .done, .error:
            return false
        }
    }

    /// Whether a tool-call block is being parsed.
    var isInsideToolCall: Bool {
        toolActive && terminal == nil
    }

    // MARK: - Streaming

    mutating func consume(_ chunk: String) -> [DS4ParsedOutputDelta] {
        guard finishedOutput == nil else {
            return []
        }
        rawText += chunk
        guard terminal == nil, !chunk.isEmpty else {
            return []
        }
        for byte in chunk.utf8 {
            if terminal != nil {
                break
            }
            if toolActive {
                feedTool(byte)
            } else {
                // One byte at a time, so the splitter never consumes a think
                // tag that belongs to a tool block opened by an earlier byte.
                handle(splitter.consumeBytes(CollectionOfOne(byte)))
            }
        }
        return drainDeltas(flushingIncompleteUTF8: false)
    }

    mutating func finish() -> DS4ParsedOutput {
        if let finishedOutput {
            return finishedOutput
        }
        if terminal == nil, !toolActive {
            handle(splitter.finishBytes())
        }
        if terminal == nil {
            flushStartTail()
        }
        if terminal == nil, toolActive {
            tool.finish()
            switch tool.state {
            case .done:
                terminal = .completed
            case .error:
                terminal = .failed(tool.errorDetail)
            case .search, .structural, .parameterValue:
                terminal = .failed("incomplete \(syntax.displayName) tool call")
            }
        }
        release(thought: false, keepingPossibleMarker: false)
        release(thought: true, keepingPossibleMarker: false)
        let finalDeltas = drainDeltas(flushingIncompleteUTF8: true)

        var parseError: DS4ToolParseError?
        var toolCalls: [DirectAgentToolCall] = []
        var replays: [DS4ToolCallReplay] = []
        switch terminal {
        case let .failed(detail):
            parseError = DS4ToolParseError(detail: detail)
        case .completed:
            (toolCalls, replays) = makeToolCalls()
        case nil:
            break
        }
        let output = DS4ParsedOutput(
            visibleText: visibleText,
            reasoningText: reasoningText,
            toolCalls: toolCalls,
            toolCallReplays: replays,
            parseError: parseError,
            rawText: rawText,
            finalDeltas: finalDeltas
        )
        finishedOutput = output
        return output
    }

    // MARK: - Routing (agent_stream_text)

    private mutating func handle(_ events: [DS4ThinkSplitter.Event]) {
        for event in events {
            guard terminal == nil else {
                return
            }
            switch event {
            case let .text(_, bytes):
                for byte in bytes {
                    guard terminal == nil else {
                        return
                    }
                    if toolActive {
                        feedTool(byte)
                    } else {
                        normalByte(byte)
                    }
                }
            case let .tag(bytes, opensThinking):
                if toolActive {
                    for byte in bytes where terminal == nil {
                        feedTool(byte)
                    }
                    continue
                }
                flushStartTail()
                guard terminal == nil else {
                    return
                }
                // A think tag breaks the displayed text: release what was held.
                release(thought: isInsideThinking, keepingPossibleMarker: false)
                if isInsideThinking {
                    thinkingMarkers.reset()
                } else {
                    plainMarkers.reset()
                }
                isInsideThinking = opensThinking
            }
        }
    }

    /// `agent_stream_normal_byte`.
    private mutating func normalByte(_ byte: UInt8) {
        if isInsideThinking, syntax.usesDSML, let marker = thinkingMarkers.feed(byte) {
            // agent_stream_note_thinking_dsml_byte: DSML in reasoning is a tool
            // call attempted too early. Hide the marker that was written so far.
            dropTrailingThought(Array(marker.dropLast()))
            release(thought: true, keepingPossibleMarker: false)
            fail(Self.thinkingToolCallDetail)
            return
        }

        if !startTail.isEmpty || byte == DS4Bytes.lessThan {
            if startTail.count < 64 {
                startTail.append(byte)
            }
            if let match = startMatch() {
                if match.complete {
                    startTool(implicitInvoke: match.implicitInvoke)
                }
                return
            }
            if startTail.count > 1, startTail.last == DS4Bytes.lessThan {
                let flushed = startTail.dropLast()
                startTail.removeAll()
                for heldByte in flushed {
                    write(heldByte)
                    if terminal != nil {
                        return
                    }
                }
                startTail = [DS4Bytes.lessThan]
                return
            }
            flushStartTail()
            return
        }
        write(byte)
    }

    /// `agent_stream_dsml_start_match`: the held tail is a prefix of an
    /// accepted opener; `complete` when it is the whole opener.
    private func startMatch() -> (complete: Bool, implicitInvoke: Bool)? {
        for form in startForms where startTail.count <= form.bytes.count {
            if DS4Bytes.hasPrefix(form.bytes, at: 0, startTail) {
                return (startTail.count == form.bytes.count, form.implicitInvoke)
            }
        }
        return nil
    }

    /// `agent_stream_start_dsml`. The parser is seeded with the canonical
    /// opener whatever tolerated form was detected.
    private mutating func startTool(implicitInvoke: Bool) {
        startTail.removeAll()
        if isInsideThinking {
            fail(Self.thinkingToolCallDetail)
            return
        }
        toolActive = true
        tool.start()
        if implicitInvoke, syntax.usesDSML {
            for byte in canonicalInvoke where terminal == nil {
                feedTool(byte)
            }
        }
    }

    private mutating func feedTool(_ byte: UInt8) {
        tool.feed(byte: byte)
        switch tool.state {
        case .done:
            terminal = .completed
        case .error:
            terminal = .failed(tool.errorDetail)
        case .search, .structural, .parameterValue:
            break
        }
    }

    /// `agent_stream_flush_start_tail`.
    private mutating func flushStartTail() {
        guard !startTail.isEmpty else {
            return
        }
        let bytes = startTail
        startTail.removeAll()
        for byte in bytes {
            write(byte)
            if terminal != nil {
                return
            }
        }
    }

    /// `renderer_write_char` + `agent_stream_note_plain_dsml_byte`.
    private mutating func write(_ byte: UInt8) {
        if isInsideThinking {
            heldThought.append(byte)
            release(thought: true, keepingPossibleMarker: true)
            return
        }
        heldVisible.append(byte)
        if syntax.usesDSML, let marker = plainMarkers.feed(byte) {
            dropTrailingVisible(marker)
            fail(Self.strayDSMLDetail)
            release(thought: false, keepingPossibleMarker: false)
            return
        }
        release(thought: false, keepingPossibleMarker: true)
    }

    private mutating func fail(_ detail: String) {
        terminal = .failed(detail)
    }

    /// Removes a just-detected visible marker from the held display bytes so it
    /// never reaches the stream.
    private mutating func dropTrailingVisible(_ marker: [UInt8]) {
        if DS4Bytes.hasSuffix(heldVisible, marker) {
            heldVisible.removeLast(marker.count)
        }
    }

    /// Removes the written part of a marker detected in reasoning: it ends
    /// either in the held reasoning bytes or in the held opener tail.
    private mutating func dropTrailingThought(_ markerPrefix: [UInt8]) {
        var combined = heldThought + startTail
        if DS4Bytes.hasSuffix(combined, markerPrefix) {
            combined.removeLast(markerPrefix.count)
        }
        heldThought = Array(combined.prefix(min(combined.count, heldThought.count)))
        startTail.removeAll()
    }

    // MARK: - Display holdback

    /// Moves held bytes of one channel to the ordered runs, keeping (when
    /// asked) the longest suffix that may still become a DSML marker.
    private mutating func release(thought isThought: Bool, keepingPossibleMarker: Bool) {
        let held = isThought ? heldThought : heldVisible
        let keep = keepingPossibleMarker && syntax.usesDSML ? Self.possibleMarkerSuffixLength(held) : 0
        let count = held.count - keep
        guard count > 0 else {
            return
        }
        if let last = runs.last, last.thought == isThought {
            runs[runs.count - 1].bytes.append(contentsOf: held.prefix(count))
        } else {
            runs.append(Run(thought: isThought, bytes: Array(held.prefix(count))))
        }
        if isThought {
            heldThought.removeFirst(count)
        } else {
            heldVisible.removeFirst(count)
        }
    }

    private static func possibleMarkerSuffixLength(_ bytes: [UInt8]) -> Int {
        DS4Bytes.longestSuffixStartingAny(bytes, markers: MarkerDetector.markers)
    }

    /// Turns the released runs into deltas. A trailing incomplete UTF-8 scalar
    /// is carried to the next drain of the same channel.
    private mutating func drainDeltas(flushingIncompleteUTF8: Bool) -> [DS4ParsedOutputDelta] {
        var deltas: [DS4ParsedOutputDelta] = []
        var pendingRuns = runs
        runs.removeAll()
        if flushingIncompleteUTF8 {
            for (isThought, carry) in [(false, undecodedVisible), (true, undecodedThought)] where !carry.isEmpty {
                if let index = pendingRuns.firstIndex(where: { $0.thought == isThought }) {
                    pendingRuns[index].bytes.insert(contentsOf: carry, at: 0)
                } else {
                    pendingRuns.append(Run(thought: isThought, bytes: carry))
                }
            }
            undecodedVisible.removeAll()
            undecodedThought.removeAll()
        }
        for run in pendingRuns {
            let bytes = (run.thought ? undecodedThought : undecodedVisible) + run.bytes
            let length = flushingIncompleteUTF8 ? bytes.count : DS4Bytes.completeUTF8PrefixLength(bytes)
            let carry = Array(bytes[length...])
            if run.thought {
                undecodedThought = carry
            } else {
                undecodedVisible = carry
            }
            guard length > 0 else {
                continue
            }
            let text = DS4Bytes.string(bytes.prefix(length))
            if run.thought {
                reasoningText += text
                if case let .thought(previous) = deltas.last {
                    deltas[deltas.count - 1] = .thought(previous + text)
                } else {
                    deltas.append(.thought(text))
                }
            } else {
                visibleText += text
                if case let .visible(previous) = deltas.last {
                    deltas[deltas.count - 1] = .visible(previous + text)
                } else {
                    deltas.append(.visible(text))
                }
            }
        }
        return deltas
    }

    // MARK: - Tool calls

    private func makeToolCalls() -> ([DirectAgentToolCall], [DS4ToolCallReplay]) {
        var toolCalls: [DirectAgentToolCall] = []
        var replays: [DS4ToolCallReplay] = []
        var usedIDs = Set<String>()
        for call in tool.calls {
            var arguments: [String: JSONValue] = [:]
            var ordered: [(key: String, value: JSONValue)] = []
            for argument in call.arguments where arguments[argument.name] == nil {
                let value = argumentValue(argument, toolName: call.name)
                arguments[argument.name] = value
                ordered.append((argument.name, value))
            }
            var id = Self.makeCallID()
            while usedIDs.contains(id) {
                id = Self.makeCallID()
            }
            usedIDs.insert(id)
            toolCalls.append(
                DirectAgentToolCall(
                    id: id,
                    name: call.name,
                    argumentsObject: arguments.mapValues(\.jsonObject),
                    argumentsJSON: JSONValue.object(arguments).compactString(sortedKeys: true)
                )
            )
            replays.append(DS4ToolCallReplay(name: call.name, argumentsJSON: DS4JSONText.object(ordered)))
        }
        return (toolCalls, replays)
    }

    private static func makeCallID() -> String {
        let hex = UUID().uuidString.replacingOccurrences(of: "-", with: "").lowercased()
        return "call_" + hex.prefix(16)
    }

    /// Interprets one raw argument value.
    ///
    /// - DSML `string="true"`: text, with the closing-tag escape undone.
    /// - DSML `string="false"` (or missing): JSON when valid, otherwise the raw
    ///   text; a parameter declared `string` keeps text unless the value is a
    ///   JSON string literal.
    /// - GLM/Qwen: text unless the value is a valid non-string JSON value
    ///   (number, boolean, null, object, array) and the parameter is not
    ///   declared `string` (ds4_server.c qwen_param_value_is_json and
    ///   qwen_param_declared_string). Text has the closing-tag escape undone.
    private func argumentValue(_ argument: DS4ToolCallStreamParser.Argument, toolName: String) -> JSONValue {
        let declared = parameterTypes[toolName]?[argument.name]
        switch syntax {
        case .dsml, .dsml41:
            if argument.markedString {
                return .string(DS4ToolTextEscaping.unescape(argument.rawValue, closingTag: syntax.parameterCloseMarker))
            }
            let decoded = DS4JSONText.decodeValue(argument.rawValue)
            if declared == .string {
                if case let .string(text) = decoded {
                    return .string(text)
                }
                return .string(argument.rawValue)
            }
            return decoded ?? .string(argument.rawValue)
        case .glm, .qwen:
            if declared != .string, let decoded = DS4JSONText.decodeValue(argument.rawValue) {
                if case .string = decoded {
                    // A quoted value is text, quotes included.
                } else {
                    return decoded
                }
            }
            return .string(DS4ToolTextEscaping.unescape(argument.rawValue, closingTag: syntax.parameterCloseMarker))
        }
    }
}
