//
//  DS4TranscriptRenderer.swift
//  ZenCODE
//
//  Builds the DS4 prompt (`[DS4TranscriptOperation]`) of a turn from the
//  `RemoteGenerationClient` session messages, replicating how ds4-agent grows
//  its token transcript:
//  - system part, `agent_worker_build_system_tokens` (ds4_agent.c:5123-5135):
//    `chat_begin`; Qwen gets its reasoning-effort text as a system message,
//    the other families `chat_append_think_prefix(mode)`; then
//    `agent_append_system_prompt` (1548-1572): DSML/DSML 4.1 tokenize the
//    tools prompt as rendered chat (4.1 after an empty system message),
//    GLM/Qwen send it as a system message; then the ZenCODE system prompt as
//    a system message prefixed by "\n\n";
//  - user messages, preceded by the system note recorded with
//    `DS4MessageKeys.hintsNote` when `/ds4 hints` changed at that boundary;
//    tool results of one round as a single `tool` observation
//    with `Tool result N (name):` headers (`agent_execute_tool_observation`,
//    9515-9536);
//  - images (only when `Context.imageFiles` is set, i.e. the model has a
//    vision encoder): a user message with images becomes one multimodal
//    `user` message (its text, then the images in order); a tool observation
//    whose results carry images becomes one multimodal `user` message with
//    the same text and headers, the images following the text of the result
//    that returned them (`agent_tool_observation_build`, 9594-9598: GLM
//    grounds images in user turns, text-only observations keep the `tool`
//    role). Without `Context.imageFiles` images are not rendered;
//  - assistant turns: the assistant prefix, the generated text and the EOS
//    token except for GLM (444-448); a turn generated by this path is replayed
//    verbatim (ds4-agent never rewrites generated tokens): with the exact token
//    ids the engine committed (`DS4TranscriptOperation.tokens`, kept in
//    `DS4MessageKeys.rawTokens`) when they were produced by the model now
//    loaded (`Context.tokenIdentity`), otherwise from its raw text. The ids
//    matter because tokenizing the text again can split it differently from
//    the sampled tokens and the common prefix with the live KV would end
//    there (a model with recurrent state then rebuilds the whole prompt);
//    other turns are synthesized from content, reasoning (only with
//    `preserveThinking`) and `DS4ToolCallRenderer`;
//  - the system prompt reminder (1536-1546, 1598-1625) after the messages
//    flagged with `DS4MessageKeys.systemReminder`;
//  - `chat_append_assistant_prefix(mode)` (10369).
//  Rendering is a pure function of the messages, so the turns already sent
//  produce the same operations and the engine reuses their KV.
//

import Foundation
import ToolCore

/// A rendered DS4 prompt.
struct DS4RenderedTranscript: Sendable {
    let operations: [DS4TranscriptOperation]
    /// Operations up to the last system prompt reminder, or, without one, up
    /// to the first user message (where ds4-agent records that the system
    /// prompt was seen).
    let reminderAnchorOperationCount: Int
    /// Index in the input messages of the last rendered message (where a new
    /// system prompt reminder is recorded), `nil` without conversation.
    let lastMessageIndex: Int?
}

/// Turns the `image_url` of a message (a data URL, a `file:` URL or an
/// absolute path) into a local image file the engine can encode.
protocol DS4ImageFileResolving: Sendable {
    /// The file holding the image, or `nil` when it cannot be read. The file
    /// stays valid until the resolver is torn down; the same `imageURL` always
    /// resolves to the same file, so the rendering is stable.
    func imageFile(forImageURL imageURL: String) -> URL?
}

enum DS4TranscriptRenderer {
    /// `AGENT_SYSTEM_PROMPT_REMINDER_TOKENS` (ds4_agent.c:1478).
    static let systemPromptReminderTokens = 50_000

    struct Context: Sendable {
        var syntax: DS4ToolSyntax
        /// Think mode of this turn (`DS4EngineABI.ThinkMode`).
        var thinkMode: Int32
        /// `DS4ToolsPrompt.toolsPrompt`, empty without tools.
        var toolsPrompt: String
        /// Replay the reasoning of synthesized assistant turns.
        var preserveThinking: Bool
        /// Extra system text after the system prompt. Not used for `/ds4 hints`:
        /// that note must not alter the initial KV prefix, so it is recorded on
        /// a user message (`DS4MessageKeys.hintsNote`).
        var systemNote: String?
        /// Set when the model has a vision encoder: images of user messages
        /// and tool results are rendered as multimodal messages with the files
        /// it returns. `nil`: images are left out.
        var imageFiles: (any DS4ImageFileResolving)?
        /// `DS4EngineInfo.tokenIdentity` of the engine the prompt is for. The
        /// token ids of a generated turn are replayed only when they carry the
        /// same identity; `nil` never replays ids.
        var tokenIdentity: String?

        init(
            syntax: DS4ToolSyntax,
            thinkMode: Int32,
            toolsPrompt: String,
            preserveThinking: Bool,
            systemNote: String? = nil,
            imageFiles: (any DS4ImageFileResolving)? = nil,
            tokenIdentity: String? = nil
        ) {
            self.syntax = syntax
            self.thinkMode = thinkMode
            self.toolsPrompt = toolsPrompt
            self.preserveThinking = preserveThinking
            self.systemNote = systemNote
            self.imageFiles = imageFiles
            self.tokenIdentity = tokenIdentity
        }
    }

    /// Renders `messages` (first message = system prompt when its role is
    /// `system`) followed by the assistant prefix of the next turn.
    static func render(messages: [[String: Any]], context: Context) -> DS4RenderedTranscript {
        var startIndex = 0
        var systemPrompt: String?
        if let first = messages.first, role(of: first) == "system" {
            systemPrompt = RemoteGenerationClient.contentString(from: first["content"])
            startIndex = 1
        }

        var operations = systemOperations(systemPrompt: systemPrompt, context: context)
        var anchor = operations.count
        var anchorIsReminder = false
        var sawUser = false
        var lastMessageIndex: Int?
        var index = startIndex
        while index < messages.count {
            let message = messages[index]
            var flagged = isReminderFlagged(message)
            switch role(of: message) {
            case "tool":
                var end = index + 1
                while end < messages.count, role(of: messages[end]) == "tool" {
                    end += 1
                }
                let group = messages[index..<end]
                operations.append(toolObservationOperation(for: group, context: context))
                flagged = group.contains(where: isReminderFlagged)
                lastMessageIndex = end - 1
                index = end
            case "assistant":
                operations.append(contentsOf: assistantOperations(for: message, context: context))
                if let observation = message[DS4MessageKeys.toolObservation] as? String {
                    operations.append(.message(role: "tool", content: observation))
                }
                lastMessageIndex = index
                index += 1
            case "system":
                operations.append(.message(
                    role: "system",
                    content: RemoteGenerationClient.contentString(from: message["content"]) ?? ""
                ))
                lastMessageIndex = index
                index += 1
            default:
                // `/ds4 hints`: the note recorded at this boundary, as ds4-agent
                // appends it to the transcript before the user message.
                if let note = hintsNote(of: message) {
                    operations.append(.message(role: "system", content: note))
                }
                operations.append(userOperation(for: message, context: context))
                if !sawUser {
                    sawUser = true
                    if !anchorIsReminder {
                        anchor = operations.count
                    }
                }
                lastMessageIndex = index
                index += 1
            }
            if flagged {
                operations.append(contentsOf: reminderOperations(systemPrompt: systemPrompt, context: context))
                anchor = operations.count
                anchorIsReminder = true
            }
        }
        operations.append(.assistantPrefix(mode: context.thinkMode))
        return DS4RenderedTranscript(
            operations: operations,
            reminderAnchorOperationCount: anchor,
            lastMessageIndex: lastMessageIndex
        )
    }

    /// `agent_worker_build_system_tokens` + `agent_append_system_prompt`.
    static func systemOperations(systemPrompt: String?, context: Context) -> [DS4TranscriptOperation] {
        var operations: [DS4TranscriptOperation] = [.begin]
        if context.syntax == .qwen {
            if let effort = DS4ThinkModeMapping.qwenReasoningEffortText(for: context.thinkMode) {
                operations.append(.message(role: "system", content: effort))
            }
        } else {
            operations.append(.thinkPrefix(mode: context.thinkMode))
        }
        if !context.toolsPrompt.isEmpty {
            if context.syntax.usesXMLToolCall {
                operations.append(.message(role: "system", content: context.toolsPrompt))
            } else {
                if context.syntax == .dsml41 {
                    operations.append(.message(role: "system", content: ""))
                }
                operations.append(.renderedChat(context.toolsPrompt))
            }
        }
        if let systemPrompt, !systemPrompt.isEmpty {
            operations.append(.message(role: "system", content: "\n\n" + systemPrompt))
        }
        if let note = context.systemNote, !note.isEmpty {
            operations.append(.message(role: "system", content: note))
        }
        return operations
    }

    /// `agent_build_system_prompt_reminder` as appended by
    /// `agent_worker_maybe_append_system_prompt_reminder`.
    static func reminderOperations(systemPrompt: String?, context: Context) -> [DS4TranscriptOperation] {
        let reminder = "\n\n[System prompt reminder follows.]\n" + context.toolsPrompt
            + "[End system prompt reminder.]\n\n"
        var operations: [DS4TranscriptOperation] = context.syntax.usesXMLToolCall
            ? [.message(role: "system", content: reminder)]
            : [.renderedChat(reminder)]
        if let systemPrompt, !systemPrompt.isEmpty {
            operations.append(.message(role: "system", content: systemPrompt))
        }
        return operations
    }

    /// One assistant turn, terminated by EOS except for GLM.
    static func assistantOperations(for message: [String: Any], context: Context) -> [DS4TranscriptOperation] {
        var operations: [DS4TranscriptOperation] = []
        if let raw = message[DS4MessageKeys.rawAssistant] as? String {
            let mode = (message[DS4MessageKeys.thinkMode] as? Int).map(Int32.init) ?? context.thinkMode
            operations.append(.assistantPrefix(mode: mode))
            if let ids = replayableTokens(of: message, context: context) {
                operations.append(.tokens(ids))
            } else if !raw.isEmpty {
                operations.append(.renderedChat(raw))
            }
        } else {
            let content = RemoteGenerationClient.contentString(from: message["content"]) ?? ""
            let toolMarkup = DS4ToolCallRenderer.renderToolCalls(
                toolCallReplays(of: message),
                syntax: context.syntax,
                hasContent: !content.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            )
            let body: String
            if context.preserveThinking, let reasoning = RemoteGenerationClient.responseReasoningText(from: message) {
                operations.append(.assistantPrefix(mode: DS4EngineABI.ThinkMode.high))
                body = closedReasoning(reasoning, syntax: context.syntax) + content + toolMarkup
            } else {
                operations.append(.assistantPrefix(mode: DS4EngineABI.ThinkMode.none))
                body = content + toolMarkup
            }
            if !body.isEmpty {
                operations.append(.renderedChat(body))
            }
        }
        if context.syntax.assistantTurnUsesEOS {
            operations.append(.endOfSequence)
        }
        return operations
    }

    /// The token ids of a generated assistant turn, when the model that
    /// produced them is the one the prompt is rendered for.
    static func replayableTokens(of message: [String: Any], context: Context) -> [Int32]? {
        guard let identity = context.tokenIdentity,
              message[DS4MessageKeys.rawTokensModel] as? String == identity else {
            return nil
        }
        return DS4MessageKeys.rawTokenIDs(of: message)
    }

    /// The tool results of one round as one observation
    /// (`agent_execute_tool_observation`).
    static func toolObservation(for messages: ArraySlice<[String: Any]>) -> String {
        toolObservationParts(for: messages) { _ in nil }.parts.joined()
    }

    /// The observation of one tool round: a `tool` message, or, when some
    /// result carries images the model can see, one multimodal `user` message
    /// (ds4_agent.c:9594-9598) with the text of the `tool` observation.
    static func toolObservationOperation(
        for messages: ArraySlice<[String: Any]>,
        context: Context
    ) -> DS4TranscriptOperation {
        guard let resolver = context.imageFiles else {
            return .message(role: "tool", content: toolObservation(for: messages))
        }
        let observation = toolObservationParts(for: messages) { message in
            imageFiles(of: message, resolver: resolver)
        }
        guard !observation.imageFiles.isEmpty else {
            return .message(role: "tool", content: toolObservation(for: messages))
        }
        return .multimodalMessage(role: "user", textParts: observation.parts, imageFiles: observation.imageFiles)
    }

    /// The text of the observation split at the images: `parts.count ==
    /// imageFiles.count + 1` and `parts.joined()` is the text-only
    /// observation. The images of a result follow its text, in result order.
    static func toolObservationParts(
        for messages: ArraySlice<[String: Any]>,
        imageFilesOf: (([String: Any]) -> [URL]?)
    ) -> (parts: [String], imageFiles: [URL]) {
        var parts: [String] = []
        var imageFiles: [URL] = []
        var text = ""
        for (offset, message) in messages.enumerated() {
            let name = RemoteGenerationClient.stringValue(message["name"])?.nilIfBlank ?? "unknown"
            text += "Tool result \(offset + 1) (\(name)):\n"
            let output = RemoteGenerationClient.contentString(from: message["content"]) ?? ""
            text += output
            if let last = output.utf8.last, last != UInt8(ascii: "\n") {
                text += "\n"
            }
            for file in imageFilesOf(message) ?? [] {
                parts.append(text)
                text = ""
                imageFiles.append(file)
            }
        }
        parts.append(text)
        return (parts, imageFiles)
    }

    /// A user message: plain text, or a multimodal message (text, then the
    /// images in order) when it carries images the model can see.
    static func userOperation(for message: [String: Any], context: Context) -> DS4TranscriptOperation {
        let text = userContent(of: message)
        guard let resolver = context.imageFiles else {
            return .message(role: "user", content: text)
        }
        let files = imageFiles(of: message, resolver: resolver)
        guard !files.isEmpty else {
            return .message(role: "user", content: text)
        }
        return .multimodalMessage(
            role: "user",
            textParts: [text] + [String](repeating: "", count: files.count),
            imageFiles: files
        )
    }

    /// The files of the images of a message, in content order. Images that
    /// cannot be resolved are left out.
    static func imageFiles(of message: [String: Any], resolver: any DS4ImageFileResolving) -> [URL] {
        RemoteGenerationClient.chatCompletionsImageContentItems(from: message["content"]).compactMap { item in
            RemoteGenerationClient.chatCompletionsImageURL(from: item).flatMap(resolver.imageFile(forImageURL:))
        }
    }

    // MARK: - Helpers

    static func role(of message: [String: Any]) -> String {
        let role = (RemoteGenerationClient.stringValue(message["role"]) ?? "")
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased()
        switch role {
        case "system", "developer":
            return "system"
        case "assistant", "tool":
            return role
        case "function":
            return "tool"
        default:
            return "user"
        }
    }

    /// The content of a user message as first sent (`DS4MessageKeys.userContent`)
    /// or its text.
    static func userContent(of message: [String: Any]) -> String {
        if let rendered = message[DS4MessageKeys.userContent] as? String {
            return rendered
        }
        return RemoteGenerationClient.contentString(from: message["content"]) ?? ""
    }

    static func isReminderFlagged(_ message: [String: Any]) -> Bool {
        message[DS4MessageKeys.systemReminder] as? Bool == true
    }

    /// The `/ds4 hints` note recorded on a user message, if any.
    static func hintsNote(of message: [String: Any]) -> String? {
        guard let note = message[DS4MessageKeys.hintsNote] as? String, !note.isEmpty else {
            return nil
        }
        return note
    }

    /// Tool calls of a synthesized assistant turn, in emission order when known.
    static func toolCallReplays(of message: [String: Any]) -> [DS4ToolCallReplay] {
        if let stored = message[DS4MessageKeys.toolCallReplays] as? [[String: String]] {
            return stored.compactMap { entry in
                guard let name = entry["name"], let arguments = entry["arguments"] else {
                    return nil
                }
                return DS4ToolCallReplay(name: name, argumentsJSON: arguments)
            }
        }
        return RemoteGenerationClient.runtimeToolCalls(from: message).map { call in
            DS4ToolCallReplay(name: call.name, argumentsJSON: call.argumentsJSON)
        }
    }

    /// Reasoning followed by the close of the think block opened by the
    /// assistant prefix (Qwen: trimmed, "\n</think>\n\n", as ds4_server.c).
    static func closedReasoning(_ reasoning: String, syntax: DS4ToolSyntax) -> String {
        switch syntax {
        case .qwen:
            reasoning.trimmingCharacters(in: .whitespacesAndNewlines) + "\n</think>\n\n"
        case .dsml, .dsml41, .glm:
            reasoning + "</think>"
        }
    }
}
